#!/usr/bin/env node
// Turn a research batch (a JS array of project records, each with a `points` list)
// into a data file the page can load.
//   node tools/import-batch.cjs <batch.js> <data/projects-name.js> "Description"
// Then add <script src="data/projects-name.js"></script> to index.html after routes.js,
// and run node tools/validate.cjs.
const fs = require("fs"), vm = require("vm");
const [, , src, out, desc = ""] = process.argv;
if (!src || !out) { console.error("usage: import-batch.js <batch.js> <out.js> [description]"); process.exit(2); }
const text = fs.readFileSync(src, "utf8").replace(/^\s*(module\.exports\s*=|export default|(const|let|var)\s+\w+\s*=)\s*/m, "");
const records = vm.runInNewContext("(" + text.trim().replace(/;\s*$/, "") + ")");
const routes = {};
for (const p of records) {
  if (Array.isArray(p.points) && p.points.length) {
    routes[p.id] = [p.points.map((pt) => [+pt[0], +pt[1], String(pt[2] || "")])];
    if (!p.location) p.location = { lat: +p.points[0][0], lng: +p.points[0][1] };
  }
  delete p.points;
  p.constituencies = p.constituencies || [];
}
const body =
  `// ${desc || out}\n// Generated by tools/import-batch.cjs from a research batch. Edit freely; schema in ../README.md.\n` +
  `(function () {\n  var D = window.PUBLIC_WORKS_DATA, R = (window.PUBLIC_WORKS_ROUTES = window.PUBLIC_WORKS_ROUTES || {});\n` +
  `  var projects = ${JSON.stringify(records, null, 2).replace(/\n/g, "\n  ")};\n` +
  `  var routes = ${JSON.stringify(routes)};\n` +
  `  projects.forEach(function (p) { D.projects.push(p); });\n  Object.keys(routes).forEach(function (k) { R[k] = routes[k]; });\n})();\n`;
fs.writeFileSync(out, body);
console.log(`${records.length} projects -> ${out}`);
