#!/usr/bin/env node
// Build data/construction.js from OpenStreetMap construction features (Overpass "out tags center meta" JSON files).
//   node tools/build-construction.cjs <fetchedAt ISO> <osm.json> [more.json ...] [--ts dates.json]
// Keeps only features inside a BMC ward. Each site carries its last OSM edit date so the page can say
// how current the "under construction" tag is. OSM is volunteer-mapped: it is not a permit register.
const fs = require("fs"), path = require("path");
const args = process.argv.slice(2); const fetchedAt = args.shift();
let tsFile = null; const ti = args.indexOf("--ts"); if (ti >= 0) { tsFile = args[ti + 1]; args.splice(ti, 2); }
global.window = {}; require(path.join(__dirname, "..", "data", "wards.js"));
const W = window.PUBLIC_WORKS_WARDS.features;
function inRing(x, y, r) { let c = false; for (let i = 0, j = r.length - 1; i < r.length; j = i++) { const [xi, yi] = r[i], [xj, yj] = r[j]; if ((yi > y) !== (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi) c = !c; } return c; }
function wardAt(lat, lng) {
  for (const f of W) { const g = f.geometry; const polys = g.type === "Polygon" ? [g.coordinates] : g.coordinates;
    for (const p of polys) if (inRing(lng, lat, p[0]) && !p.slice(1).some(h => inRing(lng, lat, h))) return f.properties.ward; }
  return null;
}
const ts = tsFile ? JSON.parse(fs.readFileSync(tsFile, "utf8")) : {};
const seen = new Map();
for (const f of args) { let els; try { els = JSON.parse(fs.readFileSync(f, "utf8")).elements || []; } catch (e) { continue; }
  for (const e of els) { const k = e.type + "/" + e.id; const prev = seen.get(k); if (!prev || (!prev.timestamp && e.timestamp)) seen.set(k, e); } }
const KIND = { residential: "Residential", apartments: "Residential", house: "Residential", commercial: "Commercial", office: "Commercial", retail: "Commercial",
  hospital: "Hospital", school: "School", train_station: "Railway", station: "Railway", industrial: "Industrial", hotel: "Hotel", road: "Road", bridge: "Bridge" };
const sites = [];
for (const [k, e] of seen) {
  const c = e.center || (e.lat != null ? { lat: e.lat, lon: e.lon } : null); if (!c) continue;
  const ward = wardAt(c.lat, c.lon); if (!ward) continue;
  const t = e.tags || {}; const edited = e.timestamp || ts[k] || null;
  sites.push({ id: k, name: t.name || t["name:en"] || null, kind: KIND[t.construction] || null,
    tagged: t.landuse === "construction" ? "landuse=construction" : "building=construction",
    operator: t.operator || t.developer || null, lat: +c.lat.toFixed(5), lng: +c.lon.toFixed(5), ward, lastEdited: edited ? edited.slice(0, 10) : null });
}
sites.sort((a, b) => (b.lastEdited || "").localeCompare(a.lastEdited || ""));
const out = { fetchedAt, source: "OpenStreetMap contributors (ODbL), via the Overpass API", sourceUrl: "https://www.openstreetmap.org/copyright",
  note: "Places volunteer mappers have tagged as a construction site. Not an official permit list: some may have finished, others are not mapped yet.", sites };
fs.writeFileSync(path.join(__dirname, "..", "data", "construction.js"),
  "// Generated by tools/build-construction.cjs from OpenStreetMap. Do not edit by hand.\nwindow.PUBLIC_WORKS_CONSTRUCTION = " + JSON.stringify(out) + ";\n");
console.log(sites.length, "sites in BMC wards;", sites.filter(s => !s.lastEdited).length, "without date;", sites.filter(s => s.name).length, "named");
