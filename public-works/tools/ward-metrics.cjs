#!/usr/bin/env node
// Per-ward measures computed from map data:
//   area (km²) from BMC ward boundaries; bus stops and rail/metro stations from OpenStreetMap;
//   share of each ward's land within 400 m of a bus stop and within 1 km of a station
//   (sampled on a ~100 m grid). Writes data/ward-metrics.js.
//   node tools/ward-metrics.cjs <busstops.json> <stations.json> [halts.json] --fetched YYYY-MM-DD
// Counts depend on how completely volunteers have mapped stops; the page says so.
const fs = require("fs"), path = require("path");
const args = process.argv.slice(2); const fi = args.indexOf("--fetched"); const fetched = fi >= 0 ? args.splice(fi, 2)[1] : null;
global.window = {}; require(path.join(__dirname, "..", "data", "wards.js"));
const W = window.PUBLIC_WORKS_WARDS.features;
const R = 6371.0088, rad = Math.PI / 180;
function polys(f) { return f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates; }
function inRing(x, y, r) { let c = false; for (let i = 0, j = r.length - 1; i < r.length; j = i++) { const [xi, yi] = r[i], [xj, yj] = r[j]; if ((yi > y) !== (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi) c = !c; } return c; }
function inWard(f, lng, lat) { return polys(f).some(p => inRing(lng, lat, p[0]) && !p.slice(1).some(h => inRing(lng, lat, h))); }
function ringArea(r) { // km², equal-area approx via spherical excess formula
  let s = 0; for (let i = 0; i < r.length - 1; i++) { const [l1, p1] = r[i], [l2, p2] = r[i + 1]; s += (l2 - l1) * rad * (2 + Math.sin(p1 * rad) + Math.sin(p2 * rad)); }
  return Math.abs(s * R * R / 2);
}
function area(f) { return polys(f).reduce((a, p) => a + ringArea(p[0]) - p.slice(1).reduce((b, h) => b + ringArea(h), 0), 0); }
function km(a, b, c, d) { const kx = 111.32 * Math.cos(a * rad); return Math.hypot((d - b) * kx, (c - a) * 110.57); }
function load(f) { try { return JSON.parse(fs.readFileSync(f, "utf8")).elements.filter(e => e.lat != null); } catch (e) { return []; } }
const bus = load(args[0]), st = load(args[1]).concat(args[2] ? load(args[2]) : []);
const isMetro = e => /subway|metro|light_rail|monorail/i.test([e.tags && e.tags.station, e.tags && e.tags.subway, e.tags && e.tags.network, e.tags && e.tags.operator, e.tags && e.tags.name].join(" "));
const out = {};
for (const f of W) {
  const w = f.properties.ward, a = area(f);
  const b = bus.filter(e => inWard(f, e.lon, e.lat)), s = st.filter(e => inWard(f, e.lon, e.lat));
  // grid sample
  let minX = 1e9, maxX = -1e9, minY = 1e9, maxY = -1e9; polys(f).forEach(p => p[0].forEach(([x, y]) => { minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y); }));
  const dy = 0.1 / 110.57, dx = 0.1 / (111.32 * Math.cos(((minY + maxY) / 2) * rad));
  const nb = bus.filter(e => e.lat > minY - 0.01 && e.lat < maxY + 0.01 && e.lon > minX - 0.01 && e.lon < maxX + 0.01);
  const ns = st.filter(e => e.lat > minY - 0.02 && e.lat < maxY + 0.02 && e.lon > minX - 0.02 && e.lon < maxX + 0.02);
  let n = 0, nbus = 0, nst = 0;
  for (let y = minY; y <= maxY; y += dy) for (let x = minX; x <= maxX; x += dx) {
    if (!inWard(f, x, y)) continue; n++;
    if (nb.some(e => km(y, x, e.lat, e.lon) <= 0.4)) nbus++;
    if (ns.some(e => km(y, x, e.lat, e.lon) <= 1)) nst++;
  }
  out[w] = { areaKm2: +a.toFixed(2), busStops: b.length, busStopsPerKm2: +(b.length / a).toFixed(1), stations: s.filter(e => !isMetro(e)).length, metroStations: s.filter(isMetro).length,
    pctNearBus: n ? Math.round(100 * nbus / n) : null, pctNearStation: n ? Math.round(100 * nst / n) : null };
}
const res = { fetched, method: "Ward area from BMC ward boundaries. Bus stops and rail/metro stations from OpenStreetMap. Walking reach: share of the ward's land (sampled every ~100 m) within 400 m of a mapped bus stop or 1 km of a mapped station. Counts depend on how completely volunteers have mapped stops.", source: "OpenStreetMap contributors (ODbL); BMC ward boundaries", wards: out };
fs.writeFileSync(path.join(__dirname, "..", "data", "ward-metrics.js"), "// Generated by tools/ward-metrics.cjs. Do not edit by hand.\nwindow.PUBLIC_WORKS_WARD_METRICS = " + JSON.stringify(res) + ";\n");
const tot = Object.values(out).reduce((a, x) => a + x.areaKm2, 0);
console.log("wards", Object.keys(out).length, "total area km2", tot.toFixed(1), "bus stops", bus.length, "stations", st.length);
