#!/usr/bin/env node
// Build data/history.js: every change to a project's status, cost, dates or progress, and to a
// corporator seat (name, party, vacancy), reconstructed from the git history of the data files.
//   node tools/build-history.cjs
// Each entry records the date the change was committed to this portal, not the date it happened
// on the ground; the page says so.
const { execSync } = require("child_process"), vm = require("vm"), fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, "..", ".."), DATA = "public-works/data/";
const PFILES = ["projects", "projects-state", "projects-bmc-infra", "projects-bmc-services", "projects-central", "projects-more"].map(f => DATA + f + ".js");
const CFILE = DATA + "corporators.js";
const sh = c => execSync(c, { cwd: ROOT, encoding: "utf8", maxBuffer: 1 << 28, stdio: ["ignore", "pipe", "ignore"] });
const commits = sh(`git log --reverse --format=%H%x20%cs -- ${PFILES.join(" ")} ${CFILE}`).trim().split("\n").filter(Boolean).map(l => { const [h, d] = l.split(" "); return { h, d }; });
function load(h, files) {
  const win = {};
  for (const f of files) { let src; try { src = sh(`git show ${h}:${f}`); } catch (e) { continue; } try { vm.runInNewContext(src, { window: win }); } catch (e) {} }
  return win;
}
function projSnap(win) {
  const out = {};
  for (const k of Object.keys(win)) { const v = win[k]; const list = Array.isArray(v) ? v : v && Array.isArray(v.projects) ? v.projects : null; if (!list || !list.length || !list[0] || !list[0].status) continue;
    for (const p of list) if (p && p.id) out[p.id] = { status: p.status, cost: p.cost ? (p.cost.revised != null ? p.cost.revised : p.cost.original) : null, targetDate: p.targetDate || null, revisedTargetDate: p.revisedTargetDate || null, completedDate: p.completedDate || null, progress: p.progress == null ? null : p.progress, name: p.shortName || p.name }; }
  return out;
}
function corSnap(win) {
  const c = win.PUBLIC_WORKS_CORPORATORS; const out = {};
  if (c && c.corporators) for (const x of c.corporators) out[x.ward] = { name: x.name || null, party: x.party || null, vacant: !!x.vacant };
  return out;
}
const LABEL = { status: "Status", cost: "Cost (₹ cr)", targetDate: "Original deadline", revisedTargetDate: "Revised deadline", completedDate: "Opened", progress: "Progress (%)", name: "Name", party: "Party", vacant: "Seat vacant" };
const projects = {}, corporators = {};
let prevP = null, prevC = null;
for (const { h, d } of commits) {
  const win = load(h, PFILES.concat([CFILE]));
  const P = projSnap(win), C = corSnap(win);
  if (Object.keys(P).length) {
    for (const id of Object.keys(P)) {
      if (!prevP || !prevP[id]) { (projects[id] = projects[id] || []).push({ date: d, field: "added", to: null }); continue; }
      for (const f of ["status", "cost", "targetDate", "revisedTargetDate", "completedDate", "progress"]) if (JSON.stringify(prevP[id][f]) !== JSON.stringify(P[id][f])) (projects[id] = projects[id] || []).push({ date: d, field: f, label: LABEL[f], from: prevP[id][f], to: P[id][f] });
    }
    prevP = P;
  }
  if (Object.keys(C).length) {
    for (const w of Object.keys(C)) {
      if (!prevC || !prevC[w]) { (corporators[w] = corporators[w] || []).push({ date: d, field: "added", to: null }); continue; }
      for (const f of ["name", "party", "vacant"]) if (JSON.stringify(prevC[w][f]) !== JSON.stringify(C[w][f])) (corporators[w] = corporators[w] || []).push({ date: d, field: f, label: LABEL[f], from: prevC[w][f], to: C[w][f] });
    }
    prevC = C;
  }
}
const out = { builtAt: new Date().toISOString().slice(0, 10), since: commits.length ? commits[0].d : null, note: "Changes recorded in this portal's data, by the date they were made here. A change here can lag the event it reflects.", projects, corporators };
fs.writeFileSync(path.join(ROOT, DATA, "history.js"), "// Generated by tools/build-history.cjs from git history. Do not edit by hand.\nwindow.PUBLIC_WORKS_HISTORY = " + JSON.stringify(out) + ";\n");
const nP = Object.values(projects).reduce((a, l) => a + l.filter(x => x.field !== "added").length, 0), nC = Object.values(corporators).reduce((a, l) => a + l.filter(x => x.field !== "added").length, 0);
console.log(commits.length, "commits;", nP, "project changes;", nC, "corporator changes; since", out.since);
